package com.omnix.assistant.voice.stt

import org.junit.Assert.assertEquals
import org.junit.Test

class AsrPostProcessorTest {

    private fun p(text: String) = AsrPostProcessor.process(text)

    @Test
    fun `пустая и пробельная строки остаются пустыми`() {
        assertEquals("", p(""))
        assertEquals("", p("   "))
    }

    @Test
    fun `обычная фраза не меняется`() {
        assertEquals("Какая сегодня погода", p("Какая сегодня погода"))
        assertEquals("включи три песни", p("включи три песни"))
        assertEquals("сколько будет пять плюс два", p("сколько будет пять плюс два"))
    }

    @Test
    fun `лишние пробелы схлопываются`() {
        assertEquals("сколько времени", p("  сколько   времени "))
    }

    @Test
    fun `позвони маме даёт имя контакта в именительном падеже`() {
        assertEquals("позвони мама", p("позвони маме"))
        assertEquals("Позвони папа", p("Позвони папе"))
        assertEquals("набери бабушка", p("набери бабушку"))
    }

    @Test
    fun `падеж не трогаем, если за словом идёт ещё текст или глагол другой`() {
        assertEquals("напомни позвонить маме", p("напомни позвонить маме"))
        assertEquals("позвони маме на работу", p("позвони маме на работу"))
        assertEquals("расскажи маме", p("расскажи маме"))
    }

    @Test
    fun `слово вызова приводится к Омни`() {
        assertEquals("Омни", p("Оми"))
        assertEquals("Омни, сколько времени", p("омме, сколько времени"))
        assertEquals("Омни сколько времени", p("Омми сколько времени"))
    }

    @Test
    fun `слово вызова вместе с командой звонка`() {
        assertEquals("Омни, позвони мама", p("Омни, позвони маме"))
        assertEquals("Омни позвони папа", p("оми позвони папе"))
    }

    @Test
    fun `слова-паразиты и заикание в начале убираются`() {
        assertEquals("позвони мама", p("эээ ну позвони позвони маме"))
        assertEquals("Включи музыку", p("Ну включи включи музыку"))
        assertEquals("Омни включи свет", p("Омни ну включи свет"))
    }

    @Test
    fun `фраза из одних паразитов не стирается`() {
        assertEquals("ну", p("ну"))
    }

    @Test
    fun `повтор вне начала фразы сохраняется`() {
        assertEquals("включи свет очень очень яркий", p("включи свет очень очень яркий"))
    }

    @Test
    fun `в шесть вечера становится цифрой`() {
        assertEquals("напомни в 6 вечера позвонить маме", p("напомни в шесть вечера позвонить маме"))
        assertEquals("напомни в 6 часов вечера купить хлеб", p("напомни в шесть часов вечера купить хлеб"))
    }

    @Test
    fun `восемнадцать ноль ноль даёт время`() {
        assertEquals("напомни в 18:00 купить хлеб", p("напомни в восемнадцать ноль ноль купить хлеб"))
        assertEquals("18:00", p("восемнадцать ноль ноль"))
    }

    @Test
    fun `часы и минуты словами`() {
        assertEquals("поставь будильник на 7:30", p("поставь будильник на семь тридцать"))
        assertEquals("напомни в 5:15 выпить воды", p("напомни в пять пятнадцать выпить воды"))
        assertEquals("напомни в 21:40 выключить плиту", p("напомни в двадцать один сорок выключить плиту"))
        assertEquals("разбуди в 7:05", p("разбуди в семь ноль пять"))
    }

    @Test
    fun `через N минут и часов`() {
        assertEquals("напомни через 20 минут выключить плиту", p("напомни через двадцать минут выключить плиту"))
        assertEquals("напомни через 2 часа позвонить", p("напомни через два часа позвонить"))
        assertEquals("напомни через 25 минут", p("напомни через двадцать пять минут"))
    }

    @Test
    fun `в три раза не принимается за время`() {
        assertEquals("сделай в три раза громче", p("сделай в три раза громче"))
        assertEquals("напомни в три раза", p("напомни в три раза"))
    }

    @Test
    fun `голое в пять считается временем только в напоминании`() {
        assertEquals("напомни в 5 позвонить", p("напомни в пять позвонить"))
        assertEquals("встреча в пять", p("встреча в пять"))
    }

    @Test
    fun `туркменские числа времени`() {
        assertEquals("ertir sagat 6:30 ýatla", p("ertir sagat alty otuz ýatla"))
        assertEquals("5 minutdan jaň et", p("bäş minutdan jaň et"))
        assertEquals("jaň et", p("jan et"))
    }

    @Test
    fun `повторная обработка ничего не меняет`() {
        val samples = listOf(
            "эээ ну позвони позвони маме",
            "оми позвони папе",
            "напомни в восемнадцать ноль ноль купить хлеб",
            "напомни через двадцать минут выключить плиту",
            "ertir sagat alty otuz ýatla",
            "Какая сегодня погода"
        )
        for (sample in samples) {
            val once = p(sample)
            assertEquals(once, p(once))
        }
    }
}
