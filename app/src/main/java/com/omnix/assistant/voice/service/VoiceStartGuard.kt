package com.omnix.assistant.voice.service

import java.io.File

/**
 * Страж петли перезапуска службы ассистента.
 *
 * Служба помечена START_STICKY: если процесс умер, Android поднимает её
 * снова. Когда смерть вызвал сам запуск голосового пайплайна (нативный сбой,
 * который не ловится в Java), это превращается в петлю — служба поднимается
 * при каждом открытии приложения и снова роняет его, в приложение не войти.
 *
 * Механика: перед запуском пайплайна ставится маркер, после
 * [SURVIVAL_MS] работы без сбоев — снимается (и при штатной остановке).
 * Если система перезапускает службу, а маркер стоит, — прошлый запуск убил
 * процесс: пайплайн не запускается, служба останавливается, ассистент
 * остаётся выключенным. Явное включение пользователем всегда разрешено.
 *
 * Чистый класс без Android-зависимостей — покрывается JVM-тестами.
 */
class VoiceStartGuard(private val markerFile: File) {

    /** Непосредственно перед запуском голосового пайплайна. */
    fun attemptStarted() {
        runCatching {
            markerFile.parentFile?.mkdirs()
            markerFile.writeText(System.currentTimeMillis().toString())
        }
    }

    /** Пайплайн проработал [SURVIVAL_MS] или служба остановлена штатно. */
    fun cleared() {
        runCatching { markerFile.delete() }
    }

    /**
     * Можно ли выполнить СИСТЕМНЫЙ перезапуск (intent == null). Ложь — прошлый
     * запуск не дожил до снятия маркера, повтор уронит приложение снова.
     */
    fun systemRestartAllowed(): Boolean = !markerFile.exists()

    companion object {
        /** Сколько пайплайн должен проработать, чтобы запуск считался удачным. */
        const val SURVIVAL_MS = 10_000L
    }
}
