package com.omnix.assistant.agent.localai.mediapipe

import java.io.File

/**
 * Страж нативного краша при ГЕНЕРАЦИИ — парный к [ModelInitCrashGuard],
 * который закрывает только загрузку модели (create()).
 *
 * addQueryChunk()/generateResponseAsync() — такие же нативные вызовы:
 * SIGSEGV/OOM-kill внутри них роняет ВЕСЬ ПРОЦЕСС, Java это не ловит, и в
 * отличие от краша при загрузке здесь не остаётся ни краш-файла, ни
 * эскалации в облако — пользователь просто вылетает из приложения.
 *
 * Механика: маркер-файл со счётчиком живёт рядом с файлом модели и
 * переживает смерть процесса. Непосредственно перед нативной генерацией
 * маркер ставится (если он уже стоит — прошлая генерация не завершилась,
 * счётчик растёт); после любого возврата в Java (успех, исключение или
 * отмена — процесс выжил) маркер снимается и счётчик обнуляется.
 *
 * ПОРОГ — две ПОСЛЕДОВАТЕЛЬНЫХ смерти процесса без единой завершённой
 * генерации между ними, а не одна, как у init-стража: окно генерации
 * длится секунды, и за это время процесс может убить система (LMK в фоне,
 * force-stop пользователя) без вины модели. Одна незавершённая генерация —
 * не приговор; две подряд — паттерн: модель запрещается до смены файла
 * (новая загрузка / переустановка / удаление), чат уходит в облако.
 *
 * Файл координирует два независимых объекта (рантайм пишет маркер во время
 * генерации, менеджер читает при загрузке) — как [ModelInitCrashGuard].
 *
 * Чистый класс без Android-зависимостей — покрывается JVM-тестами.
 */
class InferenceCrashGuard(private val markerFile: File) {

    /**
     * Вызывается НЕПОСРЕДСТВЕННО перед нативной генерацией. Найденный
     * маркер — незавершённая прошлая генерация: счётчик +1.
     */
    fun generationStarted() {
        runCatching {
            markerFile.parentFile?.mkdirs()
            val strikes = leftoverStrikes()
            markerFile.writeText((strikes + 1).toString())
        }
    }

    /**
     * Процесс выжил (генерация вернулась или бросила Java-исключение) —
     * цепочка прервана, счётчик обнуляем.
     */
    fun generationFinished() {
        runCatching { markerFile.delete() }
    }

    /** true — две последовательные генерации убили процесс: модель небезопасна. */
    fun isBanned(): Boolean = leftoverStrikes() >= BAN_THRESHOLD

    /** Незавершённые последовательные генерации (0 — маркера нет). */
    fun leftoverStrikes(): Int = runCatching {
        if (markerFile.exists()) markerFile.readText().trim().toIntOrNull() ?: 1 else 0
    }.getOrDefault(0)

    /** Новая версия файла модели — разрешаем свежие попытки. */
    fun reset() {
        runCatching { markerFile.delete() }
    }

    companion object {
        /** Сколько последовательных смертей процесса в генерации терпим. */
        const val BAN_THRESHOLD = 2
    }
}
